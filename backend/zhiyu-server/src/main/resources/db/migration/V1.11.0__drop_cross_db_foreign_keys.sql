-- 编 写 人: 资深架构师 & 数据库专家 (Antigravity AI)
-- 
-- 描述/架构说明:
--   本脚本为分布式微服务演进下的核心数据库解耦升级。
--   由于项目在 Phase 2 将认证服务 (ufp-auth-service) 进行了物理微服务剥离，并采用了完全独立的 Schema
--   (ufp_auth_dev 和 zhiyu_dev) 进行多数据源物理存储治理。
--   在微服务独立自治与分布式数据开发规范中，禁止使用物理跨库外键限制 (FOREIGN KEY)。
--   跨库物理外键会导致数据库多版本并发控制 (MVCC) 的锁级联传播，从而极易在高并发场景（如高频登录、支付）下
--   引发死锁 (Deadlock) 及锁等待超时。
-- 
-- 整改措施:
--   本脚本安全 Drop 掉核心业务表对外库 (ufp_auth.auth_user) 的 4 处跨库物理外键（user_profile 表在早期重构时已移除，对应 FK 不适用）。
--   重构后，系统将使用无损的【逻辑外键关联】来保持数据契约，关联一致性将完全交由 Java 业务层软关联保障。
-- ==============================================================================

-- ── 1. 移除 user_device 表的外键 ──────────────────────────────────────
-- 移除设备表对外部认证库 auth_user 表的物理外键关联，解除登录时的级联加锁
ALTER TABLE user_device DROP FOREIGN KEY fk_device_user;

-- ── 2. 移除 user_profile 表的外键（表在早期重构时已移除，跳过）─────
-- 用户信息表对外部认证库的物理外键关联在表迁移时已解除

-- ── 3. 移除 user_totp 表的外键 ────────────────────────────────────────
-- 移除用户TOTP表对外部认证库 auth_user 表的物理外键关联，保障二次验证并发读写性能
ALTER TABLE user_totp DROP FOREIGN KEY fk_totp_user;

-- ── 4. 移除 user_subscription 表的外键 ────────────────────────────────
-- 移除订阅表对外部认证库 auth_user 表的物理外键关联，优化订阅套餐到期处理任务性能
ALTER TABLE user_subscription DROP FOREIGN KEY fk_subscription_user;

-- ── 5. 移除 subscription_order 表的外键 ───────────────────────────────
-- 移除订单表对外部认证库 auth_user 表的物理外键关联，保证高频收银起单时事务独立自治
ALTER TABLE subscription_order DROP FOREIGN KEY fk_order_user;

-- ==============================================================================
-- 迁移完成。至此，ZhiYu 系统在数据库 Schema 层面实现 100% 独立与完全微服务去耦。
